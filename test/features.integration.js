'use strict';
const fs = require('node:fs');
module.exports = async ({ browser: b, privateWindow, shellWC: shell, root, store, writeStore, storeFile, controllers, BrowserController, check, until, wait, out }) => {
  await b.execute('settings realism strict');
  check(store.preferences.title === 'classic' && !store.preferences.notifications, 'strict preset disables browser alerts');
  b.downloadNotice('quiet.txt');
  check(!b.noticeActive, 'strict download alerts stay quiet');
  await b.execute('settings realism balanced');
  b.downloadNotice('complete.txt');
  check(b.win.getTitle().includes('Download complete: complete.txt'), 'download notification appears in native title');
  clearTimeout(b.noticeTimer); b.noticeActive = false; b.updateTitle();
  b.showPage();
  const left = b.current();
  await b.execute('split ' + root + '/split');
  await until(() => b.splitTab && !b.splitTab.view.webContents.isLoading(), 'split page');
  check(b.splitPair.length === 2 && b.splitPair.every(t => t.view.getVisible()), 'split displays two real webpages');
  await b.execute('split ratio 60');
  check(b.splitPair[0].view.getBounds().width > b.splitPair[1].view.getBounds().width, 'split ratio changes actual page bounds');
  await b.execute('split focus right');
  check(b.current() !== left && b.splitPair[0] === left, 'split focus selects right without swapping panes');
  await b.execute('workspace save Development');
  writeStore();
  check(JSON.parse(fs.readFileSync(storeFile)).workspaces[0].name === 'Development', 'named workspace persists to disk');
  const before = b.tabs.length;
  await b.execute('split off');
  check(!b.splitTab && b.tabs.length === before, 'leaving split retains both tabs');
  await b.execute('workspace open Development');
  check(b.tabs.length > before, 'saved workspace restores tabs');
  await b.execute('split off');
  await until(() => !b.current().view.webContents.isLoading(), 'workspace page ready');
  await b.execute('snapshot');
  check(fs.readFileSync(b.lastSnapshot).subarray(1, 4).toString() === 'PNG', 'snapshot saves rendered page as a real PNG');
  await b.execute('note'); await wait(100);
  check(await shell.executeJavaScript('!document.querySelector("#scratchpad").hidden && document.activeElement.id === "note-text"'), 'scratchpad opens and receives keyboard focus');
  await shell.executeJavaScript('document.querySelector("#note-text").value="A saved scratchpad"; document.querySelector("#note-text").dispatchEvent(new Event("input"));');
  await until(() => store.note === 'A saved scratchpad', 'scratchpad autosave IPC');
  await b.execute('home');
  privateWindow.saveNote('private scratchpad'); writeStore();
  check(!fs.readFileSync(storeFile, 'utf8').includes('private scratchpad'), 'private scratchpad stays out of persistent profile');
  await b.execute('watch on');
  check(b.shellView.getBounds().height <= 180 && !b.consoleVisible, 'live console docks under the webpage');
  b.recordEvent('ready', 'integration event'); await wait(100);
  check(await shell.executeJavaScript('document.querySelector("#transcript").textContent.includes("integration event")'), 'live event reaches console');
  await b.execute('watch off');
  const tabs = [...b.tabs];
  await tabs[0].view.webContents.executeJavaScript('window.preservedState = 123');
  await b.execute('settings windows on');
  check(tabs.every(t => t.owner.tabs.length === 1) && new Set(tabs.map(t => t.owner.win)).size === tabs.length, 'each tab gets its own native window');
  check(await tabs[0].view.webContents.executeJavaScript('window.preservedState === 123'), 'window migration preserves live page state');
  await b.execute('settings windows off');
  check(b.tabs.length === tabs.length && tabs.every(t => t.owner === b), 'separate windows merge back without reloading');
  await b.execute('settings console on');
  const page = b.current();
  const pageWindow = page.owner;
  check(b.consoleRole && b.consoleVisible && pageWindow !== b && !pageWindow.consoleVisible, 'persistent command prompt and webpage have separate windows');
  await b.execute('open ' + root + '/controlled');
  await until(() => page.view.webContents.getURL().endsWith('/controlled') && !page.view.webContents.isLoading(), 'console controls separate page');
  check(b.consoleVisible && !pageWindow.consoleVisible && b.current() === page, 'navigation leaves the control prompt open');
  await b.execute('new ' + root + '/new-controlled');
  await until(() => b.current().url.endsWith('/new-controlled'), 'new controlled tab');
  check(b.current().owner === pageWindow && pageWindow.tabs.length === tabs.length + 1, 'new command creates a tab in separate browser window');
  await b.execute('tabs'); await wait(100);
  check(await shell.executeJavaScript('document.querySelector("#transcript").textContent.includes("/new-controlled")'), 'control prompt lists tabs in the page window');
  await b.execute('close');
  check(!b.win.isDestroyed() && b.consoleVisible && pageWindow.tabs.length === tabs.length, 'closing a page preserves the command window');
  await b.execute('settings windows on');
  check(b.allTabs().every(e => e.controller.tabs.length === 1), 'persistent prompt also controls individual page windows');
  await b.execute('panic'); await wait(100);
  check([...controllers.values()].every(c => c.consoleVisible && c.win.getTitle() === 'Windows PowerShell'), 'disguise hides every page and title');
  b.downloadNotice('secret.txt'); check(b.win.getTitle() === 'Windows PowerShell', 'disguise suppresses download notification titles');
  check(await shell.executeJavaScript('!document.querySelector("#transcript").textContent.includes("http") && document.querySelector("#command").value === ""'), 'disguise wipes visible console addresses');
  b.showPage();
  check(b.consoleVisible && !b.current().owner.consoleVisible, 'returning from disguise restores page and keeps control prompt');
  await b.execute('settings windows off');
  await b.execute('settings console off');
  check(!b.consoleRole && b.tabs.length === tabs.length, 'separate command window can be disabled without losing tabs');
  await b.execute('settings'); await b.execute('10 on');
  check(b.consoleRole, 'numbered settings menu enables persistent command window');
  await b.execute('10 off'); await b.execute('done');
  const next = new BrowserController(false, false); await next.ready;
  check(!next.setupOpen, 'completed onboarding does not repeat on next window'); next.win.destroy();
};
